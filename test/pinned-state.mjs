import test from 'node:test'
import assert from 'node:assert/strict'
import { readFileSync, writeFileSync, readdirSync, cpSync, existsSync, rmSync } from 'node:fs'
import { join } from 'node:path'
import { api, jsonResult, readJson, commit } from './fixtures/engine-package.mjs'
import { harness, paused } from './fixtures/pinned-harness.mjs'

test('admitted real helper jobs checkpoint, resume and retain usage under N', async t => {
  await api(); const f = harness(t), p = paused(f)
  const checkpoint = readJson(p.first.checkpoint)
  assert.equal(checkpoint.executor.packageDigest, p.first.provenance.executor.packageDigest)
  assert.ok(p.first.metrics.turns > 0)
  const result = p.resume()
  assert.equal(result.status, 'done', JSON.stringify(result))
  assert.equal(result.final.readiness.state, 'ready')
  assert.ok(result.metrics.turns > p.first.metrics.turns)
  assert.ok(result.metrics.elapsedMs >= p.first.metrics.elapsedMs)
  const calls = readFileSync(f.env.FACTORY_TEST_LOG, 'utf8').trim().split('\n').map(JSON.parse)
  assert.equal(calls.filter(x => x.kind === 'intake').length, 1, 'completed intake is replayed, never re-called')
  assert.ok(readFileSync(result.hostEvents, 'utf8').includes('checkpoint.replayed'))
  assert.equal(readJson(result.summaryFile).provenance.executor.packageDigest, checkpoint.executor.packageDigest)
  assert.ok(result.provenance.inputs.gate)
  assert.ok(result.provenance.inputs.providerSettings.length > 0)
  const traces = f.traces()
  assert.ok(new Set(traces.map(x => x.pid)).size >= 3)
  assert.ok(traces.some(x => x.argv[1]?.endsWith('/lib/engine.mjs')))
  const jobs = join(result.runDir, 'jobs')
  const job = readdirSync(jobs).find(name => { try { return readJson(join(jobs, name, 'spec.json')).pin } catch { return false } })
  assert.ok(job)
  const pid = Number(readFileSync(join(jobs, job, 'pid'), 'utf8'))
  assert.ok(traces.some(x => x.ppid === pid), 'detached Python job really calls the observation adapter')
  const before = readFileSync(result.checkpoint)
  const exportFile = join(result.provenance.executor.root, 'lib/evaluate.mjs'), original = readFileSync(exportFile)
  writeFileSync(exportFile, Buffer.concat([original, Buffer.from('\n// drift')]))
  const failed = jsonResult(f.launch(['--resume', result.hostRunDir]))
  assert.equal(failed.status, 'failed'); assert.match(failed.error, /changed/)
  assert.deepEqual(readFileSync(result.checkpoint), before)
})

test('settings drift and legacy-to-pinned migration refuse before checkpoint metadata changes', async t => {
  await api(); const f = harness(t), p = paused(f)
  const before = readFileSync(p.first.checkpoint), hostBefore = readFileSync(join(p.first.hostRunDir, 'host.json'))
  f.update({ sources: { [join(f.env.CODEX_HOME, 'config.toml')]: { status: 'file', text: `sandbox_workspace_write = { writable_roots = [${JSON.stringify(f.output)}] }` } } })
  const refused = p.resume()
  assert.equal(refused.status, 'failed'); assert.match(refused.error, /overlaps|settings changed/)
  assert.deepEqual(readFileSync(p.first.checkpoint), before)
  assert.deepEqual(readFileSync(join(p.first.hostRunDir, 'host.json')), hostBefore)
  f.update({ sources: {} })
  const legacy = jsonResult(f.launch(['--workflow', 'pair', '--explain', 'Explain']))
  const migrate = jsonResult(f.launch(['--resume', legacy.hostRunDir, '--pin-engine', f.output]))
  assert.equal(migrate.status, 'failed'); assert.match(migrate.error, /migrate/)
})

test('relocated resume retains package locations and charged completed work', async t => {
  await api(); const f = harness(t), p = paused(f), relocated = join(f.dir, 'relocated')
  cpSync(f.output, relocated, { recursive: true, verbatimSymlinks: true })
  rmSync(f.output, { recursive: true })
  const result = p.resume(['--pin-engine', relocated])
  assert.equal(result.final?.readiness.state, 'ready', JSON.stringify(result))
  assert.equal(result.provenance.executor.root, join(relocated, 'plugin'))
  assert.deepEqual(result.provenance.executor.locations, [p.first.provenance.executor.root, join(relocated, 'plugin')])
  assert.deepEqual(readJson(join(result.hostRunDir, 'host.json')).provenance.executor.locations, result.provenance.executor.locations)
  const calls = readFileSync(f.env.FACTORY_TEST_LOG, 'utf8').trim().split('\n').map(JSON.parse)
  assert.equal(calls.filter(x => x.kind === 'intake').length, 1)
  assert.ok(result.metrics.turns > p.first.metrics.turns)
  assert.ok(result.metrics.elapsedMs >= p.first.metrics.elapsedMs)
})

test('relocation reuses an in-flight compatible job without a second provider call', async t => {
  const E = await api(), f = harness(t), pin = E.exportEngine(f.source, f.output, f.target)
  const helper = join(pin.root, 'bin/dark-factory'), release = join(f.dir, 'release')
  const env = { DARK_FACTORY_PIN: JSON.stringify(pin), PINNED_TINY: '1', PINNED_WAIT_FILE: release, PINNED_EXPECTED_HELPER: helper, PINNED_HELPER_TRACE: join(f.dir, 'helpers.jsonl') }
  const run = jsonResult(f.run(helper, ['init', '--repo', f.target, '--seats', 'A', '--run-id', 'relocated-cache', '--factory'], env))
  const prompt = join(f.dir, 'prompt.md'); writeFileSync(prompt, 'Check the fixture\n<<<OUTPUT_SCHEMA\n{"type":"object","properties":{"ok":{"type":"boolean"}},"required":["ok"]}\nOUTPUT_SCHEMA>>>\n')
  const args = ['seat-run', '--run-dir', run.runDir, '--seat', 'A', '--job', 'cached', '--model', 'fixture', '--effort', 'high', '--sandbox', 'workspace-write', '--cwd', run.worktrees.A, '--prompt-file', prompt, '--fresh', '--max-wait', '0']
  const first = jsonResult(f.run(helper, args, env))
  assert.equal(first.status, 'running', JSON.stringify(first))
  for (let i = 0; i < 500 && !existsSync(release + '.started'); i++) await new Promise(r => setTimeout(r, 10))
  assert.ok(existsSync(release + '.started'))
  const job = join(run.runDir, 'jobs/cached'), pid = readFileSync(join(job, 'pid'), 'utf8')
  const relocated = join(f.dir, 'relocated'); cpSync(f.output, relocated, { recursive: true, verbatimSymlinks: true })
  const newPin = E.validateExport(relocated, pin), newHelper = join(newPin.root, 'bin/dark-factory')
  const second = jsonResult(f.run(newHelper, args, { ...env, DARK_FACTORY_PIN: JSON.stringify(newPin) }))
  assert.equal(second.status, 'running', JSON.stringify(second))
  assert.equal(readFileSync(join(job, 'pid'), 'utf8'), pid)
  writeFileSync(release, 'go')
  let done = jsonResult(f.run(newHelper, ['wait', '--run-dir', run.runDir, '--job', 'cached', '--max-wait', '5'], { ...env, DARK_FACTORY_PIN: JSON.stringify(newPin) }))
  while (done.status === 'running') done = jsonResult(f.run(newHelper, ['wait', '--run-dir', run.runDir, '--job', 'cached', '--max-wait', '5'], { ...env, DARK_FACTORY_PIN: JSON.stringify(newPin) }))
  assert.equal(done.status, 'done', JSON.stringify(done))
  assert.equal(readFileSync(env.PINNED_HELPER_TRACE, 'utf8').trim().split('\n').length, 1)
  assert.equal(readFileSync(join(run.runDir, 'usage.jsonl'), 'utf8').trim().split('\n').length, 1)
})

test('live resume tolerates an unrelated commit in the separate plugin source repository', async t => {
  await api(); const f = harness(t)
  const first = jsonResult(f.launch(['--tier', 'simple', 'Fix sum'], { PINNED_INTAKE_FEATURE: '1' }))
  assert.equal(first.status, 'needs-tier', JSON.stringify(first))
  assert.equal(first.provenance.executor.mode, 'live')
  assert.ok(first.metrics.turns > 0)
  writeFileSync(join(f.source, 'README.md'), 'Unrelated source documentation\n')
  const revision = commit(f.source)
  assert.notEqual(revision, first.provenance.executor.sourceRevision)
  const answers = join(f.dir, 'answers.json'); writeFileSync(answers, JSON.stringify({ tierConfirmed: true }))
  const result = jsonResult(f.launch(['--resume', first.hostRunDir, '--args-file', answers], { PINNED_INTAKE_FEATURE: '1' }))
  assert.equal(result.final?.readiness.state, 'ready', JSON.stringify(result))
  assert.equal(result.provenance.executor.mode, 'live')
  assert.equal(result.provenance.executor.sourceRevision, revision)
  assert.equal(result.provenance.executor.packageDigest, first.provenance.executor.packageDigest)
  assert.ok(result.metrics.turns > first.metrics.turns)
  assert.ok(result.metrics.elapsedMs >= first.metrics.elapsedMs)
  const calls = readFileSync(f.env.FACTORY_TEST_LOG, 'utf8').trim().split('\n').map(JSON.parse)
  assert.equal(calls.filter(x => x.kind === 'intake').length, 1)
  assert.ok(readFileSync(result.hostEvents, 'utf8').includes('checkpoint.replayed'))
})
